CONTROL_LABELS = [
    ("per_message_mean", "Per-message mean (baseline)"),
    ("per_message_max", "Per-message max"),
    ("per_message_top5", "Per-message top-5 mean"),
    ("conv_concat", "Conversation concat (order-inv.)"),
    ("conv_mean", "Conversation mean (order-inv.)"),
    ("sequence", "Sequence (position-weighted)"),
    ("sequence_shuffled", "Sequence, shuffled order (control)"),
]


def _tab_controls(json_name, tex_name):
    d = load(json_name)
    deg = {row["strength_name"]: row["models"] for row in d["degradation"]}
    clean = {m: deg["light"][m]["auc_clean"] for m, _ in CONTROL_LABELS}
    rows = []
    for m, label in CONTROL_LABELS:
        cells = [f"{clean[m]:.3f}"]
        for s in ("light", "medium", "heavy"):
            cells.append(f"{deg[s][m]['auc_drop']:.3f}")
        bold = m == "sequence"
        lbl = f"\\textbf{{{label}}}" if bold else label
        rows.append(lbl + " & " + " & ".join(cells) + " \\\\")
    body = (
        "\\begin{tabular}{@{}l c c c c@{}}\n\\toprule\n"
        " & Clean & \\multicolumn{3}{c}{AUC drop at strength} \\\\\n"
        "\\cmidrule(lr){3-5}\n"
        "Model / control & AUC & light & medium & heavy \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    write(tex_name, json_name, body)


def tab_perturbation_controls():
    _tab_controls("perturbation_model_controls.json",
                  "tab_perturbation_controls.tex")


def tab_perturbation_second_family():
    _tab_controls("perturbation_second_family.json",
                  "tab_perturbation_second_family.tex")


def tab_perturbation_sweeps_merged():
    """Both sweep splits in one column-width-friendly table (USENIX draft)."""
    conv = {c["strength_name"]: c
            for c in load("perturbation_sweep.json")["conditions"]}
    adj = {c["strength_name"]: c
           for c in load("perturbation_sweep_author_disjoint.json")["conditions"]}
    rows = []
    for name in ("none", "light", "medium", "heavy"):
        cells = [name]
        for cond in (conv, adj):
            c0 = cond["none"]
            c = cond[name]
            for model in ("baseline", "sequence"):
                auc = c[model]["auc"]["mean"]
                drop = c0[model]["auc"]["mean"] - auc
                cells.append(f"{auc:.3f}" if name == "none"
                             else f"{auc:.3f} ({drop:.3f})")
        rows.append(" & ".join(cells) + " \\\\")
    body = (
        "\\begin{tabular}{@{}l cc cc@{}}\n\\toprule\n"
        " & \\multicolumn{2}{c}{Conversation-level split} & "
        "\\multicolumn{2}{c}{Author-disjoint split} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
        "Strength & Per-msg & Sequence & Per-msg & Sequence \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    write("tab_perturbation_sweeps_merged.tex",
          "perturbation_sweep.json + perturbation_sweep_author_disjoint.json",
          body)


def tab_perturbation_paired_tests():
    d = load("perturbation_paired_tests.json")
    label = {
        "per_message_mean": "vs.\\ per-message mean (baseline)",
        "per_message_max": "vs.\\ per-message max",
        "per_message_top5": "vs.\\ per-message top-5 mean",
        "conv_concat": "vs.\\ conversation concat (order-inv.)",
        "conv_mean": "vs.\\ conversation mean (order-inv.)",
    }
    rows = []
    for comp, per_strength in d["comparisons"].items():
        cells = []
        for s in ("light", "medium", "heavy"):
            r = per_strength[s]
            lo, hi = r["ci95"]
            mark = "$^*$" if r["ci_excludes_zero"] else ""
            cells.append(f"$[{lo:+.4f}, {hi:+.4f}]${mark}")
        rows.append(f"{label[comp]} & " + " & ".join(cells) + " \\\\")
    body = (
        "\\begin{tabular}{@{}l c c c@{}}\n\\toprule\n"
        "Comparison & light & medium & heavy \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    write("tab_perturbation_paired_tests.tex",
          "perturbation_paired_tests.json", body)


def main():
    print("Generating paper tables from experiments/results/*.json ...")
    tab_clean_detection()
    tab_minhash_frontier()
    tab_perturbation_sweep()
    tab_fp_substrate()
    for fn in (tab_perturbation_author_disjoint, tab_perturbation_controls,
               tab_perturbation_paired_tests, tab_perturbation_second_family,
               tab_perturbation_sweeps_merged):
        try:
            fn()
        except FileNotFoundError as exc:
            print(f"  SKIP {fn.__name__}: source JSON not found ({exc.filename})")
    print("Done.")


if __name__ == "__main__":
    main()
